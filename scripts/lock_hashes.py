"""Add `--hash` lines to requirements.lock from PyPI's published sha256 digests.

Every file of each pinned version is listed, so `pip install --require-hashes` works on any
platform. Run after changing pins: python scripts/lock_hashes.py
"""

from __future__ import annotations

import json
import re
import urllib.request
from pathlib import Path

LOCK = Path(__file__).resolve().parents[1] / "requirements.lock"
PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([A-Za-z0-9_.+-]+)")


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=20) as resp:  # noqa: S310 - fixed https PyPI URL
        files = json.load(resp)["urls"]
    return sorted(f["digests"]["sha256"] for f in files)


def main() -> None:
    pins = [PIN.match(line) for line in LOCK.read_text(encoding="utf-8").splitlines()]
    out = ["# Generated by scripts/lock_hashes.py; install with --require-hashes."]
    for m in filter(None, pins):
        name, version = m.groups()
        out.append(f"{name}=={version} \\")
        digests = hashes(name, version)
        out.extend(f"    --hash=sha256:{h}" + (" \\" if i < len(digests) - 1 else "") for i, h in enumerate(digests))
    LOCK.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(list(filter(None, pins)))} pins hashed")


if __name__ == "__main__":
    main()
